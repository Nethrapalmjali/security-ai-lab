import assert from 'node:assert/strict';
import { analyze, levenshtein, punycodeDecode, hostToUnicode, registrableDomain, parseIPv4Obfuscated, deLeet, scriptsOf } from './phish.js';

assert.equal(levenshtein('kitten', 'sitting'), 3);
assert.equal(levenshtein('', 'abc'), 3);
assert.equal(punycodeDecode('mnchen-3ya'), 'münchen');
assert.equal(hostToUnicode('xn--mnchen-3ya.de'), 'münchen.de');
assert.equal(registrableDomain('a.b.paypal.com'), 'paypal.com');
assert.equal(registrableDomain('login.bank.co.uk'), 'bank.co.uk');
assert.equal(parseIPv4Obfuscated('3232235777'), '192.168.1.1');
assert.equal(parseIPv4Obfuscated('0xC0.0xA8.1.1'), '192.168.1.1');
assert.equal(parseIPv4Obfuscated('0300.0250.01.01'), '192.168.1.1');
assert.equal(parseIPv4Obfuscated('example.com'), null);
assert.equal(deLeet('paypa1'), 'paypal');
assert.equal(deLeet('rnicrosoft'), 'microsoft');
assert.deepEqual(scriptsOf('раypal'), ['Cyrillic', 'Latin']);

const has = (r, re) => r.findings.some(f => re.test(f.title));
let r = analyze('https://www.paypal.com/signin');
assert.ok(r.score < 30, 'legit paypal low: ' + r.score);
assert.ok(!has(r, /Typosquat|Brand/));
r = analyze('https://github.com/anthropics');
assert.ok(r.score < 10);
r = analyze('http://paypa1.com/login');
assert.ok(has(r, /Typosquat of paypal/)); assert.ok(has(r, /Unencrypted/));
r = analyze('https://paypal.com.secure-verify.xyz/login');
assert.ok(has(r, /Brand in subdomain/)); assert.ok(r.score >= 60, 'score ' + r.score);
r = analyze('https://paypal.com@evil.example.net/');
assert.ok(has(r, /@ trick/)); assert.equal(r.meta.host, 'evil.example.net');
r = analyze('http://3232235777/login');
assert.ok(has(r, /Obfuscated IP/));
r = analyze('https://xn--pypal-4ve.com/');
assert.ok(has(r, /Punycode/)); assert.ok(has(r, /homograph/i));
r = analyze('https://bit.ly/abc');
assert.ok(has(r, /shortener/));
r = analyze('https://a.b.c.d.example.com/');
assert.ok(has(r, /Excessive subdomains/));
r = analyze('https://example.com/go?url=https://evil.test/x');
assert.ok(has(r, /redirect/));
r = analyze('javascript:alert(1)');
assert.equal(r.findings[0].severity, 'critical');
r = analyze('example.com/invoice.pdf.exe');
assert.ok(has(r, /Double file|Executable/));
assert.equal(analyze('').ok, false);
assert.equal(analyze('http://').ok, false);
r = analyze('https://g00gle-account.top/verify');
assert.ok(r.verdict !== 'No strong signals');
console.log('all tests passed');
